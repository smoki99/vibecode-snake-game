#!/usr/bin/env node
/**
 * Sprite generator. assets/icons/icon-*.svg are the source of truth; assets/icons/sprite.svg is a
 * build artifact assembled from them.
 *
 *   node tools/sprite.mjs            # regenerate assets/icons/sprite.svg
 *   node tools/sprite.mjs --check    # exit 1 if the committed sprite differs (used by tests)
 *
 * Output is deterministic: names sorted, no timestamps, so a diff means a real change. The test
 * suite regenerates the sprite and diffs it, which is what stops the bundle and the files drifting
 * apart.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const DIR = new URL('../assets/icons/', import.meta.url).pathname;
const PRESENTATION = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin'];

/** A symbol id must be addressable from CSS and from <use href="#...">. */
export const ICON_ID_PATTERN = /^icon-[a-z0-9]+(-[a-z0-9]+)*$/;

/** Pull the root presentation attributes and the inner markup out of an icon file. */
export function parseIcon(source, name) {
  const match = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/);
  if (!match) throw new Error(`${name}: not a well-formed svg file`);
  const [, attrs, inner] = match;
  const kept = PRESENTATION.map((key) => {
    const found = attrs.match(new RegExp(`${key}="([^"]*)"`));
    return found ? `${key}="${found[1]}"` : null;
  }).filter(Boolean);
  // <title> lives in the source file for humans previewing it; consumers label their own controls.
  const body = inner
    .replace(/\n?\s*<title>[\s\S]*?<\/title>/g, '')
    .trim()
    .split('\n')
    .map((line) => `    ${line.trim()}`)
    .join('\n');
  const viewBox = (attrs.match(/viewBox="([^"]*)"/) || [, '0 0 24 24'])[1];
  return { id: name.replace(/^icon-/, '').replace(/\.svg$/, ''), attrs: kept, body, viewBox };
}

export function buildSprite(icons) {
  const symbols = icons
    .map(({ id, attrs, body, viewBox }) => {
      if (!ICON_ID_PATTERN.test(`icon-${id}`)) {
        throw new Error(`invalid icon file name "icon-${id}.svg"; expected icon-<slug>.svg`);
      }
      const attrText = [`id="icon-${id}"`, `viewBox="${viewBox}"`, ...attrs].join(' ');
      return `  <symbol ${attrText}>\n${body}\n  </symbol>`;
    })
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/sprite.mjs from assets/icons/icon-*.svg. Do not hand-edit. -->
<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" style="display:none">
${symbols}
</svg>
`;
}

export async function loadIcons(dir = DIR) {
  const files = (await readdir(dir)).filter((n) => n.endsWith('.svg') && n !== 'sprite.svg').sort();
  // A typo'd file name must fail loudly: silently skipping it would drop an icon from the sprite.
  for (const file of files) {
    if (!ICON_ID_PATTERN.test(file.replace(/\.svg$/, ''))) {
      throw new Error(`invalid icon file name "${file}"; expected icon-<slug>.svg`);
    }
  }
  const icons = [];
  for (const file of files) icons.push(parseIcon(await readFile(join(dir, file), 'utf8'), file));
  return icons;
}

async function main() {
  const check = process.argv.includes('--check');
  const sprite = buildSprite(await loadIcons());
  const target = join(DIR, 'sprite.svg');
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => null);
    if (current !== sprite) {
      console.error('sprite.svg is out of date - run: node tools/sprite.mjs');
      process.exitCode = 1;
      return;
    }
    console.log('sprite.svg matches its sources');
    return;
  }
  await writeFile(target, sprite);
  console.log(`sprite.svg written with ${(sprite.match(/<symbol /g) || []).length} symbols`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => {
    console.error(err.message);
    process.exitCode = 1;
  });
}
